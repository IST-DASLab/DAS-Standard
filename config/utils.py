def compute_max_iters(cfg, attn_fn, mlp_fn):
    """
    This function computes the number of iterations based on some number of
    parameters for the model (can be full model size of
    chinchilla token ratio and batch size / grad acc steps / seq len.

    We only count the number of linear layers in transformer blocks (Attn & MLP)
    """
    L = cfg.model.num_layers
    S = cfg.model.seq_len
    B = cfg.training.local_batch_size
    A = cfg.training.grad_acc_steps
    CTR = cfg.training.chinchilla_token_ratio

    params_count = L * (attn_fn(cfg) + mlp_fn(cfg))
    num_tokens = params_count * CTR * 20
    iterations = math.ceil(num_tokens / (B * S * A))

    return iterations


def print_config(cfg: ArgParseNamespace):
    """
    Displays the values of the config field by field.
    Handles the nested Namespace -> Dataclass structure generated by simple_parsing.
    """
    print("=" * 60)
    print(f"{'EXPERIMENT CONFIGURATION':^60}")
    print("=" * 60)

    # Iterate over the top-level groupings (e.g., 'training', 'model', 'optimizer')
    for section_name, section_config in vars(cfg).items():
        print(f"\n[{section_name.upper()}]")

        # Convert the underlying object to a dictionary for printing
        if is_dataclass(section_config):
            config_dict = asdict(section_config)
        elif hasattr(section_config, '__dict__'):
            config_dict = vars(section_config)
        elif isinstance(section_config, dict):
            config_dict = section_config
        else:
            print(f"  {section_config}")
            continue

        # Print each field aligned for readability
        for key, value in config_dict.items():
            print(f"  {key:<25} : {value}")

    print("\n" + "=" * 60)